"""Deterministic SYNTHETIC demo data for the Mega Campus model.

Run:  python -m airgrid.demo_seed [--plans-dir <dir with ground_floor.png first_floor.png second_floor.png>]

Creates (idempotently) one campus, the MEGA-MAIN building, three floors and one survey session per floor whose
points are generated by a fixed formula (distance decay from assumed AP positions plus a fixed pseudo-noise term).
Every point is stored with data_provenance="controlled_test_import" and a SYNTHETIC DEMO note. This is NOT a measurement
and NOT a radio-propagation simulation; it exists so the 3D campus, heatmap and Copilot workflows can be demonstrated.
It never touches existing rows and never scans a network.
"""
import argparse
import asyncio
import math
import shutil
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from sqlalchemy import select

from airgrid.core.database import AsyncSessionLocal
from airgrid.models.all_models import Building, Campus, Floor, FloorPlanAsset, SurveyMeasurement, SurveySession
from airgrid.services import campus_model as cm
from airgrid.services.campus_service import get_secure_upload_dir

CAMPUS_CODE = "MEGA-DEMO"
NOTE = "SYNTHETIC DEMO: generated by a fixed formula, not measured"
# assumed AP positions (Blender metres) per floor: fewer APs on upper floors give weak areas; the second floor's NE corner is left unsurveyed to show unknown coverage
APS = {0: [(-30, 20), (30, 20), (0, -20)], 1: [(-30, 20), (30, -20)], 2: [(-25, 0), (25, 0)]}
PLAN_FILES = {0: "ground_floor.png", 1: "first_floor.png", 2: "second_floor.png"}


def synthetic_rssi(floor_number: int, x: float, y: float) -> float:
    """Deterministic: strongest AP by log-distance decay, plus a +-2.5 dB term derived from the coordinates."""
    best = max(-35.0 - 30.0 * math.log10(math.hypot(x - ax, y - ay) + 1.0) for ax, ay in APS[floor_number])
    noise = 2.5 * math.sin(x * 12.9898 + y * 78.233 + floor_number)
    return round(max(-95.0, min(-30.0, best + noise)), 1)


def grid_points(step: float = 8.0, floor_number: int = 0):
    xs = [-44 + step * i for i in range(int(88 / step) + 1)]
    ys = [-28 + step * j for j in range(int(56 / step) + 1)]
    pts = [(x, y) for x in xs for y in ys]
    return [(x, y) for x, y in pts if not (floor_number == 2 and x >= 28 and y >= 12)]  # unsurveyed NE corner on floor 2


async def seed(plans_dir: Optional[Path]) -> dict:
    geom = cm.load_geometry()
    if not geom:
        raise SystemExit("Campus model metadata not found (set AIRGRID_CAMPUS_MODEL_DIR).")
    async with AsyncSessionLocal() as db:
        existing = (await db.execute(select(Campus).where(Campus.code == CAMPUS_CODE))).scalar_one_or_none()
        if existing:
            return {"created": False, "campus_id": str(existing.id)}
        campus = Campus(id=uuid.uuid4(), name="AirGrid Mega Campus (Synthetic Demo)", code=CAMPUS_CODE, status="active")
        db.add(campus)
        await db.flush()
        b = Building(id=uuid.uuid4(), campus_id=campus.id, name="Main Academic Building", building_code=cm.MODEL_BUILDING_CODE,
                     status="active", floors_count=3)
        db.add(b)
        await db.flush()
        out = {"created": True, "campus_id": str(campus.id), "building_id": str(b.id), "floors": {}}
        for fg in geom["floors"]:
            n, cal = fg["index"], fg["calibration"]
            floor = Floor(id=uuid.uuid4(), building_id=b.id, floor_number=n, name=fg["title"], status="active",
                          dimensions_width_m=96.0, dimensions_height_m=64.0)
            db.add(floor)
            await db.flush()
            if plans_dir and (plans_dir / PLAN_FILES[n]).is_file():
                dest = Path(get_secure_upload_dir()) / f"{floor.id}.png"
                shutil.copyfile(plans_dir / PLAN_FILES[n], dest)
                db.add(FloorPlanAsset(id=uuid.uuid4(), floor_id=floor.id, file_path=str(dest), file_format="png",
                                      original_filename=PLAN_FILES[n], file_size_bytes=dest.stat().st_size,
                                      pixel_width=cal["resolution_px"][0], pixel_height=cal["resolution_px"][1],
                                      scale_pixels_per_meter=cal["pixels_per_metre"], is_calibrated=True,
                                      calibration_metadata={"source": "blender_export", "synthetic_demo": True}))
            sess = SurveySession(id=uuid.uuid4(), campus_id=campus.id, building_id=b.id, floor_id=floor.id,
                                 session_name=f"SYNTHETIC DEMO survey - {fg['title']}", description=NOTE,
                                 started_at=datetime.now(timezone.utc), status="completed")
            db.add(sess)
            await db.flush()
            pts = grid_points(floor_number=n)
            for x, y in pts:
                px, py = cm.world_to_pixel(x, y, cal)
                db.add(SurveyMeasurement(id=uuid.uuid4(), survey_session_id=sess.id, floor_id=floor.id, position_x=px, position_y=py,
                                         normalized_x=px / cal["resolution_px"][0], normalized_y=py / cal["resolution_px"][1],
                                         rssi_dbm=synthetic_rssi(n, x, y), measurement_source="controlled_test_import",
                                         network_label="DEMO", data_provenance="controlled_test_import", notes=NOTE))
            out["floors"][fg["id"]] = {"floor_id": str(floor.id), "session_id": str(sess.id), "points": len(pts)}
        await db.commit()
        return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--plans-dir", type=Path, default=None, help="folder with the three floor-plan PNG renders (optional)")
    print(asyncio.run(seed(ap.parse_args().plans_dir)))


if __name__ == "__main__":
    main()
